def _find_repo_root() -> str:
    """Find the repo root by looking for the addon directory."""
    # Start from this script's location (_misc/)
    script_dir = os.path.dirname(os.path.abspath(__file__))
    candidate = os.path.dirname(script_dir)  # repo root
    if os.path.isdir(os.path.join(candidate, ADDON_DIR)):
        return candidate
    # Fallback: cwd
    return os.getcwd()


def _read_file(path: str) -> str:
    """Read a file and return its content."""
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def _parse_manifest(repo_root: str) -> dict:
    """Parse blender_manifest.toml and return key metadata."""
    path = os.path.join(repo_root, MANIFEST_PATH)
    if not os.path.exists(path):
        return {"version": "?", "blender_min": "?", "name": "?", "tagline": "?", "permissions": ""}
    content = _read_file(path)
    result = {}
    for m in re.finditer(r'^(\w+)\s*=\s*"([^"]*)"', content, re.MULTILINE):
        result[m.group(1)] = m.group(2)
    # Parse permissions section
    perm_match = re.search(r'\[permissions\]\s*\n\s*(\w+)\s*=\s*"([^"]*)"', content)
    if perm_match:
        result["permission_name"] = perm_match.group(1)
        result["permission_desc"] = perm_match.group(2)
    return result


def _parse_changelog(repo_root: str) -> list[dict]:
    """Parse CHANGELOG.md and return list of version sections."""
    path = os.path.join(repo_root, CHANGELOG_PATH)
    if not os.path.exists(path):
        return []
    content = _read_file(path)
    versions = []
    current = None
    for line in content.split("\n"):
        m = re.match(r'^## \[(v[\d.]+)\]\s*(?:-?\s*(.*))?$', line)
        if m:
            if current:
                versions.append(current)
            current = {"version": m.group(1), "date": m.group(2) or "", "lines": []}
        elif current and line.strip():
            current["lines"].append(line)
    if current:
        versions.append(current)
    return versions


def _scan_operators(repo_root: str) -> list[dict]:
    """Scan all operator files and extract operator metadata via AST."""
    operators = []
    addon_path = os.path.join(repo_root, ADDON_DIR)

    # Files to scan for operators (not just operators_*.py)
    scan_files = []
    for fname in sorted(os.listdir(addon_path)):
        if fname.endswith(".py") and (
            fname.startswith("operators_") or
            fname in ("preferences.py", "ui_chat.py")
        ):
            scan_files.append(fname)

    for fname in scan_files:
        filepath = os.path.join(addon_path, fname)
        with open(filepath, "r", encoding="utf-8") as fh:
            tree = ast.parse(fh.read(), filename=filepath)

        for node in ast.walk(tree):
            if not isinstance(node, ast.ClassDef):
                continue
            # Must inherit from bpy.types.Operator or bpy.types.AddonPreferences
            is_operator = False
            for base in node.bases:
                if isinstance(base, ast.Attribute) and base.attr in ("Operator", "AddonPreferences"):
                    is_operator = True
                elif isinstance(base, ast.Name) and base.id in ("Operator", "AddonPreferences"):
                    is_operator = True
            if not is_operator:
                continue

            op = {
                "class_name": node.name,
                "module": fname,
                "bl_idname": "",
                "bl_label": "",
                "bl_description": "",
                "docstring": ast.get_docstring(node) or "",
            }
            # Extract bl_idname, bl_label, bl_description from class body
            for item in node.body:
                if isinstance(item, ast.Assign):
                    for target in item.targets:
                        if isinstance(target, ast.Name):
                            if target.id == "bl_idname" and isinstance(item.value, ast.Constant):
                                op["bl_idname"] = item.value.value
                            elif target.id == "bl_label" and isinstance(item.value, ast.Constant):
                                op["bl_label"] = item.value.value
                            elif target.id == "bl_description" and isinstance(item.value, ast.Constant):
                                op["bl_description"] = item.value.value
            operators.append(op)
    return operators


def _scan_mcp_tools(repo_root: str) -> list[dict]:
    """Scan MCP tools directory and extract tool metadata via AST."""
    tools = []
    tools_path = os.path.join(repo_root, MCP_TOOLS_DIR)
    if not os.path.isdir(tools_path):
        return tools
    for fname in sorted(os.listdir(tools_path)):
        if not fname.endswith(".py"):
            continue
        if fname.endswith("_toolcode.py"):
            continue
        if fname == "__init__.py":
            continue
        filepath = os.path.join(tools_path, fname)
        with open(filepath, "r", encoding="utf-8") as fh:
            tree = ast.parse(fh.read(), filename=filepath)

        for node in ast.walk(tree):
            if not isinstance(node, ast.FunctionDef):
                continue
            # Check for @mcp.tool() decorator
            has_decorator = False
            for dec in node.decorator_list:
                if isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute):
                    if dec.func.attr == "tool":
                        has_decorator = True
                        break
            if not has_decorator:
                continue

            # Skip CLI variants (e.g., execute_blender_code_for_cli)
            if node.name.endswith("_for_cli"):
                continue

            docstring = ast.get_docstring(node) or ""
            first_para = docstring.split("\n\n")[0].strip()
            description = " ".join(first_para.split())

            tools.append({
                "name": node.name,
                "description": description,
                "docstring": docstring,
                "module": fname,
            })
    return tools


def _scan_preferences(repo_root: str) -> list[dict]:
    """Scan preferences.py and extract property metadata via AST."""
    props = []
    path = os.path.join(repo_root, ADDON_DIR, "preferences.py")
    if not os.path.exists(path):
        return props
    content = _read_file(path)
    tree = ast.parse(content, filename=path)

    # Find the _BFACW_Preferences class
    for node in ast.walk(tree):
        if not isinstance(node, ast.ClassDef):
            continue
        if node.name != "_BFACW_Preferences":
            continue

        for item in node.body:
            # Handle both annotated assignments (host: StringProperty(...))
            # and regular assignments (host = StringProperty(...))
            prop_name = None
            prop_value = None

            if isinstance(item, ast.AnnAssign):
                if isinstance(item.target, ast.Name):
                    prop_name = item.target.id
                    # In Blender preferences, the property call is the annotation
                    # e.g., host: StringProperty(name="Host", ...)
                    prop_value = item.annotation
            elif isinstance(item, ast.Assign):
                for target in item.targets:
                    if isinstance(target, ast.Name):
                        prop_name = target.id
                        prop_value = item.value
                        break

            if prop_name is None or prop_value is None:
                continue

            # Skip internal/private properties
            if prop_name.startswith("_"):
                continue

            # Check if the value is a property call
            if not isinstance(prop_value, ast.Call):
                continue
            func = prop_value.func
            if not isinstance(func, ast.Name):
                continue
            prop_type = func.id
            # Only capture Blender property types
            if not prop_type.endswith("Property"):
                continue

            # Extract name and description from keyword arguments
            prop_label = prop_name
            prop_desc = ""
            for kw in prop_value.keywords:
                if kw.arg == "name" and isinstance(kw.value, ast.Constant):
                    prop_label = kw.value.value
                elif kw.arg == "description" and isinstance(kw.value, ast.Constant):
                    prop_desc = kw.value.value

            # Determine which tab this property belongs to
            tab = _classify_pref_tab(prop_name, prop_label, prop_desc)

            props.append({
                "name": prop_name,
                "label": prop_label,
                "type": prop_type,
                "description": prop_desc,
                "tab": tab,
            })
    return props


def _classify_pref_tab(name: str, label: str, desc: str) -> str:
    """Classify a preference property into its tab."""
    # Bridge server properties
    if name in ("host", "port", "use_autostart", "autostart_delay", "use_log",
                 "timer_interval_active", "timer_interval_idle", "timer_interval_idle_delay"):
        return "Advanced"
    # LLM properties
    if name in ("llm_mode", "llama_path", "model_repo_id", "model_filename",
                 "downloaded_models_dir", "model_preset", "model_preset_info",
                 "existing_model_path", "local_ctx_size", "local_ctx_preset",
                 "local_max_tokens", "reasoning_effort", "thinking_budget_tokens",
                 "local_kv_cache_quant", "hf_token"):
        return "Local LLM"
    # Remote API properties
    if name in ("remote_api_url", "remote_api_key", "remote_provider",
                 "remote_model", "remote_models_count", "remote_models_fetch_error"):
        return "Remote API"
    # Generative AI properties
    if name in ("gen_backend", "gen_models_dir", "gen_output_dir", "gen_auto_download",
                 "gen_comfyui_url", "gen_remote_url", "gen_remote_key"):
        return "Generative"
    # Advanced properties
    if name in ("operating_mode", "agent_mode", "agent_autostart",
                 "mcp_server_mode", "mcp_server_host", "mcp_server_port_override",
                 "use_blender_python_for_harness", "harness_preset",
                 "port_offset", "bridge_port", "mcp_port", "llm_port",
                 "custom_skills_text", "save_code_to_text_editor",
                 "lock_scene_while_working", "reset_scene_on_failure",
                 "saved_providers_json", "pref_tab"):
        return "Advanced"
    return "Other"


def _scan_module_index(repo_root: str) -> list[dict]:
    """Index all Python modules in the addon directory."""
    modules = []
    addon_path = os.path.join(repo_root, ADDON_DIR)
    for root, dirs, files in os.walk(addon_path):
        # Skip vendor and __pycache__
        dirs[:] = [d for d in dirs if d not in ("vendor", "__pycache__", ".git")]
        for fname in sorted(files):
            if not fname.endswith(".py"):
                continue
            full_path = os.path.join(root, fname)
            rel_path = os.path.relpath(full_path, addon_path)
            with open(full_path, "r", encoding="utf-8") as fh:
                tree = ast.parse(fh.read(), filename=full_path)
            docstring = ast.get_docstring(tree) or ""
            # Extract __all__ exports
            exports = []
            for node in ast.walk(tree):
                if isinstance(node, ast.Assign):
                    for target in node.targets:
                        if isinstance(target, ast.Name) and target.id == "__all__":
                            if isinstance(node.value, ast.Tuple) or isinstance(node.value, ast.List):
                                for elt in node.value.elts:
                                    if isinstance(elt, ast.Constant):
                                        exports.append(elt.value)
            modules.append({
                "path": rel_path,
                "docstring": docstring.split("\n\n")[0].strip() if docstring else "",
                "exports": exports,
            })
    return modules


def _scan_skills(repo_root: str) -> list[dict]:
    """Scan skills directory and return skill file metadata."""
    skills = []
    skills_path = os.path.join(repo_root, SKILLS_DIR)
    if not os.path.isdir(skills_path):
        return skills
    for fname in sorted(os.listdir(skills_path)):
        if not fname.endswith(".md"):
            continue
        full_path = os.path.join(skills_path, fname)
        content = _read_file(full_path)
        # Extract first heading as title
        title_match = re.search(r'^#\s+(.+)$', content, re.MULTILINE)
        title = title_match.group(1) if title_match else fname
        skills.append({
            "filename": fname,
            "title": title,
            "content_preview": content[:200] + "..." if len(content) > 200 else content,
        })
    return skills


def _scan_gen_plugins(repo_root: str) -> list[dict]:
    """Scan gen_plugins directory and return plugin metadata."""
    plugins = []
    plugins_path = os.path.join(repo_root, GEN_PLUGINS_DIR)
    if not os.path.isdir(plugins_path):
        return plugins
    for root, dirs, files in os.walk(plugins_path):
        dirs[:] = [d for d in dirs if d.startswith("_")]
        for fname in sorted(files):
            if not fname.endswith(".py"):
                continue
            if fname == "__init__.py" or fname == "base.py":
                continue
            full_path = os.path.join(root, fname)
            rel_dir = os.path.relpath(root, plugins_path)
            with open(full_path, "r", encoding="utf-8") as fh:
                tree = ast.parse(fh.read(), filename=full_path)
            docstring = ast.get_docstring(tree) or ""
            plugins.append({
                "path": os.path.join(rel_dir, fname),
                "docstring": docstring.split("\n\n")[0].strip() if docstring else "",
            })
    return plugins


def _scan_harness_presets(repo_root: str) -> list[dict]:
    """Scan shared.py and extract external harness preset metadata via AST.

    Reads the ``HarnessPreset(...)`` calls in the ``_HARNESS_PRESETS`` list so
    the External Harness wiki page always matches the shipped presets.
    """
    presets: list[dict] = []
    path = os.path.join(repo_root, SHARED_PATH)
    if not os.path.exists(path):
        return presets
    with open(path, "r", encoding="utf-8") as fh:
        tree = ast.parse(fh.read(), filename=path)

    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        func = node.func
        if not (isinstance(func, ast.Name) and func.id == "HarnessPreset"):
            continue
        preset: dict = {"setup_steps": []}
        for kw in node.keywords:
            if kw.arg is None:
                continue
            value = kw.value
            if isinstance(value, ast.Constant):
                preset[kw.arg] = value.value
            elif isinstance(value, (ast.List, ast.Tuple)):
                preset[kw.arg] = [
                    elt.value for elt in value.elts if isinstance(elt, ast.Constant)
                ]
        if preset.get("identifier"):
            presets.append(preset)
    return presets


