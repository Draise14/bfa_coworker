SCREENSHOT = '> 📸 **SCREENSHOT NEEDED:** {caption}\n>\n> - **Where:** {where}\n> - **State:** {state}\n> - **Callouts:** {callouts}\n'


def _screenshot(caption, where, state, callouts):
    """Return a formatted screenshot placeholder blockquote."""
    return SCREENSHOT.format(caption=caption, where=where, state=state, callouts=callouts)


# Screenshots live in the wiki repo under WIKI_IMAGES; a page shows the image
# when the file exists in the output folder, otherwise a placeholder.
WIKI_IMAGES = "images/v1.1.40"
WIKI_RAW_BASE = "https://raw.githubusercontent.com/wiki/Draise14/bfa_coworker/"
_OUTPUT_DIR = ""  # set by main()


def _image(name, caption, where="", state="", callouts=""):
    """An embedded screenshot ``WIKI_IMAGES/<name>.png``, or a placeholder if missing."""
    rel = "{:s}/{:s}.png".format(WIKI_IMAGES, name)
    if _OUTPUT_DIR and os.path.exists(os.path.join(_OUTPUT_DIR, rel)):
        return "![{0:s}]({1:s}{2:s})\n\n*{0:s}*\n".format(caption, WIKI_RAW_BASE, rel)
    return _screenshot(caption, where or "-", state or "-", callouts or "-")


