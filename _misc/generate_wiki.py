def generate_preferences_reference(prefs: list[dict]) -> str:
    """Generate Preferences-Reference.md."""
    # Group by tab
    tabs = {}
    for p in prefs:
        tab = p['tab']
        if tab not in tabs:
            tabs[tab] = []
        tabs[tab].append(p)

    result = _header("Preferences Reference", f"All {len(prefs)} configurable properties") + f"""

---

## Summary

The add-on exposes **{len(prefs)} configurable properties** through the `_BFACW_Preferences` class, organized across 4 tabs.

"""

    for tab_name in ["Local LLM", "Remote API", "Generative", "Advanced"]:
        tab_prefs = tabs.get(tab_name, [])
        result += f"\n---\n\n## {tab_name} ({len(tab_prefs)} properties)\n\n"
        if tab_prefs:
            result += _table(
                ["Property", "Type", "Label", "Description"],
                [
                    [f"`{p['name']}`", f"`{p['type']}`", p['label'], p['description'].split('\n')[0] if p['description'] else ""]
                    for p in tab_prefs
                ]
            ) + "\n"

    return result


